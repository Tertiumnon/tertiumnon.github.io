import { execFileSync } from "node:child_process";
import * as fs from "node:fs/promises";
import { GITHUB_USER } from "../../../src/app/entities/github-repo/github-repo.data";

const CACHE_FILE = "scripts/project/dates--create/cache.json";
const MANUAL_FILE = "scripts/project/dates--create/manual-dates.json";
const GITHUB_PROJECTS_FILE = "src/assets/projects/github-projects.json";
const DATES_JSON = "src/assets/project-dates.json";
const CACHE_TTL_MS = 7 * 24 * 60 * 60 * 1000;

type Source = { id: string; repo: string; releasedAt?: string };
type Cache = Record<string, { date: string; checkedAt: string }>;

// Repos come from the list generated by github-projects--create, so renamed or removed repos are skipped.
const readSources = async (): Promise<Source[]> => {
	const projects = JSON.parse(await fs.readFile(GITHUB_PROJECTS_FILE, { encoding: "utf-8" })) as {
		name: string;
		version?: { date: string };
	}[];
	return [
		...projects.map(
			(project): Source => ({ id: `github:${project.name}`, repo: project.name, releasedAt: project.version?.date }),
		),
		{ id: "github:app-port-convention", repo: "app-port-convention" },
	];
};

const readManual = async (): Promise<Record<string, string>> =>
	JSON.parse(await fs.readFile(MANUAL_FILE, { encoding: "utf-8" })) as Record<string, string>;

const readCache = async (): Promise<Cache> => {
	try {
		return JSON.parse(await fs.readFile(CACHE_FILE, { encoding: "utf-8" })) as Cache;
	} catch {
		return {};
	}
};

// Commits that only maintain project.yml (site listing, attributes) are not project updates, so they do not move the date.
const HOUSEKEEPING_COMMIT = /^(chore|fix)\(project\):/;

const fetchGithubDate = (repo: string): string => {
	const commits = JSON.parse(
		execFileSync("gh", ["api", `repos/${GITHUB_USER}/${repo}/commits?per_page=100`], { encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 }),
	) as { commit: { message: string; committer: { date: string } } }[];
	const update = commits.find((item) => !HOUSEKEEPING_COMMIT.test(item.commit.message));
	if (!update) throw new Error(`No commits other than project.yml maintenance in the last 100 of GitHub repo ${repo}`);
	return update.commit.committer.date.slice(0, 10);
};

const main = async (): Promise<void> => {
	const refresh = process.argv.includes("--refresh");
	const sources = await readSources();
	const cache = await readCache();
	const manual = await readManual();
	const dates: Record<string, string> = {};
	const now = new Date().toISOString();
	let fetched = 0;

	try {
		for (const source of sources) {
			if (manual[source.id] !== undefined) {
				dates[source.id] = manual[source.id];
				continue;
			}
			// A released project is as new as its latest release; repository-wide maintenance commits would hide that.
			if (source.releasedAt !== undefined) {
				dates[source.id] = source.releasedAt;
				continue;
			}
			const cached = cache[source.id];
			const fresh = cached !== undefined && Date.now() - Date.parse(cached.checkedAt) < CACHE_TTL_MS;
			if (!refresh && fresh) {
				dates[source.id] = cached.date;
				continue;
			}
			const date = fetchGithubDate(source.repo);
			cache[source.id] = { date, checkedAt: now };
			dates[source.id] = date;
			fetched++;
		}
	} finally {
		await fs.writeFile(CACHE_FILE, `${JSON.stringify(cache, null, 2)}\n`);
	}

	for (const [id, date] of Object.entries(manual)) {
		if (id.startsWith("manual:")) dates[id] = date;
	}

	const sorted = Object.fromEntries(Object.entries(dates).sort(([a], [b]) => a.localeCompare(b)));
	await fs.writeFile(DATES_JSON, `${JSON.stringify(sorted, null, 2)}\n`);
	console.log(`Project dates: ${Object.keys(sorted).length} total, ${fetched} fetched, ${Object.keys(sorted).length - fetched} from cache.`);
};

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
